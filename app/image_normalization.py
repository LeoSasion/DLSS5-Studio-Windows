"""Normalize orientation and ICC color without truncating 16-bit image input.

Pillow's RGB decoder exposes 16-bit RGB PNGs as 8-bit RGB. The high-precision
path therefore decodes with FFmpeg, maps ICC colors with Windows' 16-bit ICM
API, and streams an explicitly sRGB 16-bit PNG. An SDR 16-bit image stays SDR.
"""
import array
import ctypes
import io
import os
import shutil
import struct
import subprocess
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageCms, ImageOps


def srgb_profile():
    profile = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
    # Profile creation time does not change pixels. A fixed header keeps
    # normalized uploads content-identical across reuploads and restarts.
    profile[24:36] = struct.pack(">6H", 2000, 1, 1, 0, 0, 0)
    profile[84:100] = b"\0" * 16
    return bytes(profile)


def equivalent_profile(a, b):
    # ICC header timestamps and profile IDs may differ between equivalent
    # profiles generated by the same CMM. Do not infer color space from a name.
    def normalized(value):
        data = bytearray(value)
        if len(data) >= 128:
            data[24:36] = b"\0" * 12
            data[84:100] = b"\0" * 16
        return data
    return normalized(a) == normalized(b)


class ColorTransform16:
    """Windows ICM, BM_16b_RGB = packed little-endian 48-bit RGB.

    See Microsoft TranslateBitmapBits / BMFORMAT / PROFILE documentation.
    Alpha is kept separately and never sent through the color transform.
    """
    def __init__(self, source_profile, destination_profile):
        if os.name != "nt":
            raise ValueError("16 位 ICC 色彩转换需要 Windows 色彩管理。")
        from ctypes import wintypes as w
        class Profile(ctypes.Structure):
            _fields_ = [("kind", w.DWORD), ("data", ctypes.c_void_p), ("size", w.DWORD)]
        self.cms = ctypes.WinDLL("mscms", use_last_error=True)
        self.cms.OpenColorProfileW.argtypes = [ctypes.POINTER(Profile), w.DWORD, w.DWORD, w.DWORD]
        self.cms.OpenColorProfileW.restype = ctypes.c_void_p
        self.cms.CloseColorProfile.argtypes = [ctypes.c_void_p]
        self.cms.CreateMultiProfileTransform.argtypes = [ctypes.POINTER(ctypes.c_void_p), w.DWORD,
            ctypes.POINTER(w.DWORD), w.DWORD, w.DWORD, w.DWORD]
        self.cms.CreateMultiProfileTransform.restype = ctypes.c_void_p
        self.cms.DeleteColorTransform.argtypes = [ctypes.c_void_p]
        self.cms.TranslateBitmapBits.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int,
            w.DWORD, w.DWORD, w.DWORD, ctypes.c_void_p, ctypes.c_int, w.DWORD, ctypes.c_void_p, ctypes.c_ssize_t]
        self.cms.TranslateBitmapBits.restype = w.BOOL
        self.buffers, self.profiles, self.transform = [], [], None
        try:
            for data in (source_profile, destination_profile):
                buffer = ctypes.create_string_buffer(data)
                self.buffers.append(buffer)
                descriptor = Profile(2, ctypes.cast(buffer, ctypes.c_void_p), len(data))  # PROFILE_MEMBUFFER
                handle = self.cms.OpenColorProfileW(ctypes.byref(descriptor), 1, 1, 3)  # PROFILE_READ / OPEN_EXISTING
                if not handle:
                    raise ValueError("无法读取图片中的 ICC 色彩配置。")
                self.profiles.append(handle)
            handles = (ctypes.c_void_p * 2)(*self.profiles)
            intent = w.DWORD(1)  # INTENT_RELATIVE_COLORIMETRIC
            self.transform = self.cms.CreateMultiProfileTransform(handles, 2, ctypes.byref(intent), 1, 3, 0)
            if not self.transform:
                raise ValueError("无法将此 ICC 配置转换为 sRGB，请重新导出图片。")
        except Exception:
            self.close()
            raise

    def convert(self, source, width, height, gray=False):
        expected = width * height * (1 if gray else 3)
        if len(source) != expected:
            raise ValueError("高精度图片数据长度无效。")
        output = array.array("H", [0]) * (width * height * 3)
        a = (ctypes.c_ushort * len(source)).from_buffer(source)
        b = (ctypes.c_ushort * len(output)).from_buffer(output)
        if not self.cms.TranslateBitmapBits(self.transform, a, 0x505 if gray else 0xA,
                width, height, width * (2 if gray else 6), b, 0xA, width * 6, None, 0):
            raise ValueError("高精度 ICC 色彩转换失败。")
        return output

    def close(self):
        if self.transform:
            self.cms.DeleteColorTransform(self.transform)
            self.transform = None
        for handle in self.profiles:
            self.cms.CloseColorProfile(handle)
        self.profiles = []


def png_chunk(stream, kind, data):
    stream.write(struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff))


def write_png16(raw_path, output, width, height, profile, transform=None, gray=False):
    """Bounded-memory row tiles, including profile conversion and PNG compression."""
    compressor = zlib.compressobj(4)
    with Path(raw_path).open("rb") as source, Path(output).open("wb") as target:
        target.write(b"\x89PNG\r\n\x1a\n")
        png_chunk(target, b"IHDR", struct.pack(">IIBBBBB", width, height, 16, 6, 0, 0, 0))
        png_chunk(target, b"iCCP", b"sRGB\0\0" + zlib.compress(profile))
        for first in range(0, height, 64):
            rows = min(64, height - first)
            data = source.read(width * rows * 8)
            if len(data) != width * rows * 8:
                raise ValueError("高精度图片解码未完成。")
            rgba = array.array("H")
            rgba.frombytes(data)
            if sys.byteorder != "little":
                rgba.byteswap()
            if transform:
                rgb = rgba[0::4] if gray else array.array("H", [0]) * (width * rows * 3)
                if not gray:
                    rgb[0::3], rgb[1::3], rgb[2::3] = rgba[0::4], rgba[1::4], rgba[2::4]
                mapped = transform.convert(rgb, width, rows, gray)
                rgba[0::4], rgba[1::4], rgba[2::4] = mapped[0::3], mapped[1::3], mapped[2::3]
            if sys.byteorder == "little":
                rgba.byteswap()
            packed = rgba.tobytes()
            stride = width * 8
            for row in range(rows):
                encoded = compressor.compress(b"\0" + packed[row * stride:(row + 1) * stride])
                if encoded:
                    png_chunk(target, b"IDAT", encoded)
        encoded = compressor.flush()
        if encoded:
            png_chunk(target, b"IDAT", encoded)
        png_chunk(target, b"IEND", b"")


def normalize(path, output, ffmpeg):
    path, output = Path(path), Path(output)
    profile_out = srgb_profile()
    with Image.open(path) as original:
        width, height = original.size
        if original.format == "TIFF":
            width = int(original.tag_v2.get(256, width))
            height = int(original.tag_v2.get(257, height))
        # Reading TIFF EXIF may make Pillow's decoder apply orientation in
        # memory; keep the file's stored dimensions before requesting it.
        try:
            orientation = int(original.getexif().get(274, 1) or 1)
        except (ValueError, TypeError) as exc:
            raise ValueError("图片方向标记无效，请重新导出。") from exc
        if orientation not in range(1, 9):
            raise ValueError("图片方向标记无效，请重新导出。")
        if orientation in {5, 6, 7, 8}:
            width, height = height, width
        profile_in = original.info.get("icc_profile")
        frames = int(getattr(original, "n_frames", 1) or 1)
        depth = 8
        with path.open("rb") as source:
            header = source.read(29)
        if header[:8] == b"\x89PNG\r\n\x1a\n":
            depth = header[24]
        elif original.format == "TIFF":
            bits = original.tag_v2.get(258, (8,))
            depth = max(bits if isinstance(bits, tuple) else (bits,))
        if depth <= 8:
            image = ImageOps.exif_transpose(original)
            if profile_in:
                try:
                    source_profile = ImageCms.ImageCmsProfile(io.BytesIO(profile_in))
                    alpha = image.convert("RGBA").getchannel("A")
                    if image.mode not in {"RGB", "CMYK", "LAB", "L"}:
                        image = image.convert("RGB")
                    image = ImageCms.profileToProfile(image, source_profile,
                        ImageCms.ImageCmsProfile(io.BytesIO(profile_out)), outputMode="RGB", renderingIntent=1)
                    image.putalpha(alpha)
                except (OSError, ValueError, ImageCms.PyCMSError) as exc:
                    raise ValueError("图片 ICC 配置无法正确转换，请重新导出为 sRGB。") from exc
            image.convert("RGBA").save(output, icc_profile=profile_out)
            return {"width": width, "height": height, "bit_depth": 8, "color_space": "sRGB", "icc_converted": bool(profile_in)}
        if depth > 16:
            raise ValueError("暂不将浮点 HDR 图片隐式压缩为 SDR，请先导出 16 位 RGB 图片。")
        gray = False
        if profile_in:
            try:
                source_profile = ImageCms.ImageCmsProfile(io.BytesIO(profile_in))
                space = source_profile.profile.xcolor_space.strip()
            except (OSError, ValueError, ImageCms.PyCMSError) as exc:
                raise ValueError("图片 ICC 配置无法读取，请重新导出。") from exc
            if space not in {"RGB", "GRAY"}:
                raise ValueError("高位深图片需使用 RGB 或灰度 ICC 配置，请先转换为 16 位 RGB。")
            gray = space == "GRAY"
    with Image.open(path) as validate:
        try:
            validate.verify()
        except SyntaxError as exc:
            raise ValueError("图片内容校验失败，请重新导出。") from exc
    if path.suffix.lower() == ".png" and frames == 1 and orientation == 1 and (not profile_in or equivalent_profile(profile_in, profile_out)):
        shutil.copy2(path, output)
        return {"width": width, "height": height, "bit_depth": 16,
                "color_space": "sRGB" if profile_in else "untagged RGB", "icc_converted": False}
    if not ffmpeg:
        raise ValueError("缺少高精度图片解码组件，请重新解压完整安装包。")
    filters = {2: ["hflip"], 3: ["hflip", "vflip"], 4: ["vflip"], 5: ["transpose=clock", "hflip"],
               6: ["transpose=clock"], 7: ["transpose=clock", "vflip"], 8: ["transpose=cclock"]}.get(orientation, [])
    raw = output.with_suffix(".rgba16.tmp")
    transform = None
    try:
        command = [ffmpeg, "-y", "-v", "error", "-noautorotate", "-i", str(path), "-frames:v", "1",
                   "-vf", ",".join(filters + ["format=rgba64le"]), "-f", "rawvideo", str(raw)]
        result = subprocess.run(command, capture_output=True, timeout=120,
                                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        if result.returncode:
            raise ValueError("高精度图片无法解码：" + result.stderr.decode("utf-8", "replace")[-500:])
        if profile_in and not equivalent_profile(profile_in, profile_out):
            transform = ColorTransform16(profile_in, profile_out)
        write_png16(raw, output, width, height, profile_out, transform, gray)
    finally:
        if transform:
            transform.close()
        raw.unlink(missing_ok=True)
    return {"width": width, "height": height, "bit_depth": 16, "color_space": "sRGB", "icc_converted": bool(transform)}
